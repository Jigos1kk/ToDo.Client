import { z } from 'zod';

/** Правила пароля синхронизированы с PasswordStrengthAttribute бэкенда. */
export const passwordSchema = z
  .string()
  .min(1, 'Пароль обязателен.')
  .min(8, 'Пароль должен содержать не менее 8 символов.')
  .max(100, 'Пароль не может превышать 100 символов.')
  .refine((value) => /[a-zа-яё]/.test(value), 'Пароль должен содержать строчную букву.')
  .refine((value) => /[A-ZА-ЯЁ]/.test(value), 'Пароль должен содержать заглавную букву.')
  .refine((value) => /\d/.test(value), 'Пароль должен содержать цифру.')
  .refine((value) => /[^\p{L}\d]/u.test(value), 'Пароль должен содержать специальный символ.');

export const emailSchema = z
  .email({ message: 'Некорректный формат email.' })
  .min(1, 'Email обязателен.')
  .max(256, 'Email не может превышать 256 символов.');

/** Правила имени пользователя синхронизированы с RegisterRequest бэкенда. */
export const userNameSchema = z
  .string()
  .min(1, 'Имя пользователя обязательно.')
  .min(3, 'Имя пользователя должно содержать от 3 до 100 символов.')
  .max(100, 'Имя пользователя должно содержать от 3 до 100 символов.')
  .regex(
    /^[\p{L}0-9_.-]+$/u,
    'Имя пользователя может содержать только буквы, цифры и символы _, ., -.',
  );
